def load():
    skills = json.loads((ROOT / "data/skills.json").read_text())
    summary = json.loads((ROOT / "data/summary.json").read_text())
    postings = json.loads((ROOT / "data/postings.json").read_text())
    bank = {}
    for p in sorted((ROOT / "bank").glob("*.yml")):
        d = yaml.safe_load(p.read_text())
        bank[d["domain"]] = d
    return skills, summary, postings, bank


def bar(pct: float, cls: str = "") -> str:
    return f'<span class="barwrap"><span class="bar {cls}" style="--w:{min(100, pct):.0f}%"></span><span class="pct">{pct:.0f}%</span></span>'


def md_cell(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def esc(s: str) -> str:
    return html.escape(str(s), quote=True)


def write(path: str, text: str):
    p = ROOT / path
    p.parent.mkdir(parents=True, exist_ok=True)
    if not p.exists() or p.read_text() != text:
        p.write_text(text)


def card_tags(c) -> str:
    tracks = " ".join(f'<span class="tag tag-track">{t.upper()}</span>' for t in c["tracks"])
    return (f'<span class="tag tag-{c["level"]}">{c["level"]}</span>'
            f'<span class="tag tag-type">{TYPE_NAME[c["type"]]}</span>{tracks}')


def one_line(s: str) -> str:
    return re.sub(r"\s+", " ", str(s)).strip()


def area_page(dom, bank_d, skill_names, n_posts) -> str:
    did, name = dom["id"], dom["name"]
    b = bank_d or {}
    cards = b.get("cards") or []
    by_skill = collections.defaultdict(list)
    for c in cards:
        by_skill[c["skill"]].append(c)
    out = [f'---\ntitle: "{name}"\nsubtitle: "Named in {dom["pct_any"]:.0f}% of {n_posts} senior postings · {len(cards)} review cards"\n'
           f"toc: true\ntoc-depth: 3\n---\n\n{GEN}"]
    if b.get("summary"):
        out.append(one_line(b["summary"]) + "\n")
    rounds = "".join(f'<span class="chip">{esc(r)}</span>' for r in b.get("rounds") or [])
    out.append(f'\n<p class="area-meta">{rounds}<a class="btn-review" href="../review/index.html#area={did}">Review these cards →</a></p>\n')

    out.append("\n## What the postings ask for\n\nShare of postings that name each skill, overall and by track.\n")
    out.append("\n| Skill | All postings | MLE | AI eng | Research eng | Cards |\n|:--|:--|--:|--:|--:|--:|\n")
    for s in dom["skills"]:
        bt = s["by_track"]
        out.append(f'| [{md_cell(s["name"])}](#{s["id"]}) | {bar(s["pct"])} | {bt.get("mle", 0):.0f}% | '
                   f'{bt.get("ai-engineer", 0):.0f}% | {bt.get("research-engineer", 0):.0f}% | {len(by_skill.get(s["id"], []))} |\n')
    quotes = []
    for s in dom["skills"][:8]:
        for q in s["quotes"][:1]:
            quotes.append((s["name"], q))
    if quotes:
        out.append("\n### In the postings' words\n\n")
        for sname, q in quotes[:7]:
            out.append(f'> {md_cell(q["text"])}\n>\n> <span class="quote-src">[{esc(q["company"])} · {esc(q["title"])}]({q["url"]})</span>\n\n')

    if b.get("senior_bar"):
        out.append("\n## The senior bar\n\nWhat separates a senior answer from a mid-level one in this area.\n\n")
        out += [f"- {one_line(x)}\n" for x in b["senior_bar"]]

    checklist = {e["skill"]: e["items"] for e in b.get("checklist") or []}
    if cards:
        out.append("\n## Skills, checklists and questions\n\nTick an item when you can explain it without notes; ticks are saved in this browser. "
                   "Open a question to see the answer.\n")
        order = [s["id"] for s in dom["skills"]] if dom["skills"] else list(by_skill)
        extra = [k for k in by_skill if k not in order]
        for sid in order + extra:
            cs = by_skill.get(sid, [])
            if not cs and sid not in checklist:
                continue
            s = next((x for x in dom["skills"] if x["id"] == sid), None)
            title = skill_names.get(sid, sid)
            demand = f' <span class="demand">{s["pct"]:.0f}% of postings</span>' if s else ""
            out.append(f"\n### {title}{demand} {{#{sid}}}\n\n")
            for i, item in enumerate(checklist.get(sid, [])):
                out.append(f'- <input type="checkbox" class="chk" data-chk="{did}.{sid}.{i}"> {one_line(item)}\n')
            out.append("\n")
            for c in cs:
                out.append(f'<details class="qa" id="{c["id"]}">\n<summary>{card_tags(c)} {one_line(c["q"])}</summary>\n\n{c["a"].rstrip()}\n\n')
                if c.get("probes"):
                    out.append("**Follow-ups**\n\n" + "".join(f"- {one_line(p)}\n" for p in c["probes"]) + "\n")
                out.append("</details>\n\n")
    else:
        out.append("\n*Review cards for this area are not written yet.*\n")

    if b.get("notes"):
        out.append("\n## Deep dives on this site\n\n")
        for n in b["notes"]:
            t = note_title(n)
            out.append(f"- [{t}](../{n})\n")
    return "".join(out)


def note_title(path: str) -> str:
    p = ROOT / path
    if p.exists():
        m = re.search(r'(?m)^title:\s*"?(.+?)"?\s*$', p.read_text()[:600])
        if m:
            return m.group(1)
    return pathlib.Path(path).stem.replace("_", " ")


def skills_index(skills, bank, n_posts, summary) -> str:
    out = [f'---\ntitle: "Skill map"\nsubtitle: "Every skill named in {n_posts} senior MLE, AI engineer and research engineer postings"\ntoc: true\ntoc-depth: 2\n---\n\n{GEN}'
           f"{len(skills['domains'])} areas, ordered as an interview loop meets them. Each bar is the share of postings that name the skill. "
           "Each area page has the demand table, the senior bar, a checklist and the questions; the [review app](../review/index.qmd) drills the same cards with spaced repetition.\n\n"
           '<div id="map-progress"></div>\n\n']
    out.append("| Area | Postings naming it | Skills | Cards |\n|:--|:--|--:|--:|\n")
    for d in skills["domains"]:
        nc = len((bank.get(d["id"]) or {}).get("cards") or [])
        out.append(f'| [{d["name"]}]({d["id"]}.qmd) | {bar(d["pct_any"])} | {len(d["skills"])} | {nc} |\n')
    if "cases" in bank:
        out.append(f'| [ML and AI system design cases](cases.qmd) | <span class="muted">the design round in every loop</span> | | {len(bank["cases"]["cards"])} |\n')
    for d in skills["domains"]:
        out.append(f'\n## {d["name"]} {{#{d["id"]}}}\n\n[Open the area page]({d["id"]}.qmd)\n\n| Skill | All | MLE | AI eng | Research eng |\n|:--|:--|--:|--:|--:|\n')
        for s in d["skills"]:
            bt = s["by_track"]
            out.append(f'| [{md_cell(s["name"])}]({d["id"]}.qmd#{s["id"]}) | {bar(s["pct"])} | {bt.get("mle", 0):.0f}% | '
                       f'{bt.get("ai-engineer", 0):.0f}% | {bt.get("research-engineer", 0):.0f}% |\n')
    return "".join(out)


def cases_page(b) -> str:
    cards = b["cards"]
    out = [f'---\ntitle: "{b.get("title", "ML and AI system design cases")}"\nsubtitle: "{len(cards)} worked design rounds"\ntoc: true\ntoc-depth: 2\n---\n\n{GEN}',
           one_line(b.get("summary", "")) + "\n",
           '\n<p class="area-meta">' + "".join(f'<span class="chip">{esc(r)}</span>' for r in b.get("rounds") or []) +
           '<a class="btn-review" href="../review/index.html#area=cases">Review these cards →</a></p>\n']
    if b.get("senior_bar"):
        out.append("\n## What the interviewer grades\n\n" + "".join(f"- {one_line(x)}\n" for x in b["senior_bar"]))
    out.append("\n## Cases\n\nTry each one on paper for 35 minutes before opening the answer.\n\n")
    for c in cards:
        out.append(f'<details class="qa" id="{c["id"]}">\n<summary>{card_tags(c)} {one_line(c["q"])}</summary>\n\n{c["a"].rstrip()}\n\n')
        if c.get("probes"):
            out.append("**Follow-ups**\n\n" + "".join(f"- {one_line(p)}\n" for p in c["probes"]) + "\n")
        out.append("</details>\n\n")
    return "".join(out)


def review_page(skills, bank, skill_names) -> str:
    order = [d["id"] for d in skills["domains"]] + ["cases"]
    n = sum(len((bank.get(a) or {}).get("cards") or []) for a in order)
    out = ['---\ntitle: "Review"\nsubtitle: "' + str(n) + ' cards · spaced repetition · progress by skill and track"\ntoc: false\npage-layout: full\n'
           "format:\n  html:\n    css: app.css\n    include-after-body:\n      - text: |\n          <script src=\"skills.js\"></script>\n          <script src=\"app.js\"></script>\n"
           "resources:\n  - skills.js\n  - app.js\n---\n\n" + GEN,
           '\n<div id="rv-app"><noscript>The review app needs JavaScript. Every card is also on the skill pages.</noscript></div>\n\n'
           '::::: {#rv-bank}\n\n']
    for a in order:
        for c in (bank.get(a) or {}).get("cards") or []:
            also = " ".join(c.get("also") or [])
            out.append(f'\n:::: {{.rv-card data-id="{c["id"]}" data-area="{a}" data-skill="{c["skill"]}" data-also="{also}" '
                       f'data-type="{c["type"]}" data-level="{c["level"]}" data-tracks="{" ".join(c["tracks"])}"}}\n\n'
                       f'::: {{.rv-q}}\n{one_line(c["q"])}\n:::\n\n::: {{.rv-a}}\n{c["a"].rstrip()}\n:::\n\n')
            if c.get("probes"):
                out.append("::: {.rv-probes}\n" + "".join(f"- {one_line(p)}\n" for p in c["probes"]) + ":::\n\n")
            out.append("::::\n")
    out.append("\n:::::\n")
    return "".join(out)


def skills_js(skills, bank) -> str:
    areas = []
    for d in skills["domains"]:
        areas.append(dict(id=d["id"], name=d["name"], short=SHORT.get(d["id"], d["name"]), pct=d["pct_any"],
                          skills=[dict(id=s["id"], name=s["name"], pct=s["pct"],
                                       mle=s["by_track"].get("mle", 0), ai=s["by_track"].get("ai-engineer", 0),
                                       re=s["by_track"].get("research-engineer", 0)) for s in d["skills"]]))
    if "cases" in bank:
        areas.append(dict(id="cases", name="ML and AI system design cases", short=SHORT["cases"], pct=100, skills=[]))
    card_skill = {c["id"]: c["skill"] for b in bank.values() for c in b.get("cards") or []}
    return "window.PREP_SKILLS = " + json.dumps(dict(n=skills["n"], areas=areas, cards=card_skill), ensure_ascii=False) + ";\n"


def postings_js(postings, summary) -> str:
    slim = [dict(t=p["title"], c=p["company"], g=p["group"], k=p["track"], a=p["archetype"], l=p["level"], y=p["yoe"],
                 p=p["pay"], loc=p["locations"][:3], us=p["us"], u=p["url"], d=p["posted"], s=p["skills"]) for p in postings]
    return ("window.PREP_POSTINGS = " + json.dumps(slim, ensure_ascii=False) + ";\n"
            "window.PREP_NAMES = " + json.dumps(summary["names"], ensure_ascii=False) + ";\n")


def report_tables(skills, summary, bank, skill_names):
    n = skills["n"]
    names = summary["names"]
    flat = [dict(s, area=d["id"], area_name=d["name"]) for d in skills["domains"] for s in d["skills"]]
    g = {}

    def dim_table(key, label):
        rows = summary["dims"][key]
        t = f"| {label} | Postings | Share |\n|:--|--:|:--|\n"
        for k, v in rows.items():
            t += f"| {names[key].get(k, k)} | {v} | {bar(100 * v / n)} |\n"
        return t

    g["sample_track"] = dim_table("track", "Track")
    g["sample_archetype"] = dim_table("archetype", "Role archetype")
    g["sample_group"] = dim_table("group", "Employer type")
    g["sample_level"] = dim_table("level", "Level in title")

    top = sorted(flat, key=lambda s: -s["pct"])
    t = "| # | Skill | Area | All postings | MLE | AI eng | Research eng |\n|--:|:--|:--|:--|--:|--:|--:|\n"
    for i, s in enumerate(top[:50], 1):
        bt = s["by_track"]
        t += (f'| {i} | [{md_cell(s["name"])}](../skills/{s["area"]}.qmd#{s["id"]}) | {SHORT[s["area"]]} | {bar(s["pct"])} | '
              f'{bt.get("mle", 0):.0f}% | {bt.get("ai-engineer", 0):.0f}% | {bt.get("research-engineer", 0):.0f}% |\n')
    g["top_skills"] = t

    # hard technical skills only (drop the senior-scope area) per track, with lift against the other tracks
    for tk, tname, _ in TRACKS:
        rows = sorted((s for s in flat if s["area"] != "senior"), key=lambda s: -s["by_track"].get(tk, 0))[:25]
        t = f"| # | Skill | Area | {tname} postings | All postings |\n|--:|:--|:--|:--|--:|\n"
        for i, s in enumerate(rows, 1):
            t += (f'| {i} | [{md_cell(s["name"])}](../skills/{s["area"]}.qmd#{s["id"]}) | {SHORT[s["area"]]} | '
                  f'{bar(s["by_track"].get(tk, 0))} | {s["pct"]:.0f}% |\n')
        g[f"track_{tk}"] = t
        others = [x for x, _, _ in TRACKS if x != tk]
        dist = sorted((s for s in flat if s["by_track"].get(tk, 0) >= 8),
                      key=lambda s: -(s["by_track"].get(tk, 0) - max(s["by_track"].get(o, 0) for o in others)))[:12]
        t = f"| Skill | {tname} | " + " | ".join(n2 for x, n2, _ in TRACKS if x != tk) + " |\n|:--|--:|--:|--:|\n"
        for s in dist:
            t += (f'| [{md_cell(s["name"])}](../skills/{s["area"]}.qmd#{s["id"]}) | **{s["by_track"].get(tk, 0):.0f}%** | ' +
                  " | ".join(f'{s["by_track"].get(o, 0):.0f}%' for o in others) + " |\n")
        g[f"distinct_{tk}"] = t

    t = ""
    for aid, cnt in summary["dims"]["archetype"].items():
        rows = sorted((s for s in flat if s["area"] != "senior"), key=lambda s: -(s["by_archetype"].get(aid, 0) - s["pct"]))[:8]
        t += f'\n**{names["archetype"][aid]}** ({cnt} postings). Over-represented skills: '
        t += "; ".join(f'{s["name"]} ({s["by_archetype"].get(aid, 0):.0f}% vs {s["pct"]:.0f}%)' for s in rows) + ".\n"
    g["archetypes"] = t

    t = ""
    for gid, cnt in summary["dims"]["group"].items():
        rows = sorted((s for s in flat if s["area"] != "senior"), key=lambda s: -(s["by_group"].get(gid, 0) - s["pct"]))[:8]
        t += f'\n**{names["group"][gid]}** ({cnt} postings). Over-represented skills: '
        t += "; ".join(f'{s["name"]} ({s["by_group"].get(gid, 0):.0f}% vs {s["pct"]:.0f}%)' for s in rows) + ".\n"
    g["groups"] = t

    lv = [l for l in ("senior", "staff", "principal") if l in summary["dims"]["level"]]
    rows = sorted((s for s in flat if s["by_level"].get("senior", 0) >= 5 or s["by_level"].get("staff", 0) >= 5),
                  key=lambda s: -(max(s["by_level"].get("staff", 0), s["by_level"].get("principal", 0)) - s["by_level"].get("senior", 0)))[:14]
    t = "| Skill | " + " | ".join(names["level"][l] for l in lv) + " |\n|:--|" + "--:|" * len(lv) + "\n"
    for s in rows:
        t += f'| {md_cell(s["name"])} | ' + " | ".join(f'{s["by_level"].get(l, 0):.0f}%' for l in lv) + " |\n"
    g["levels"] = t

    t = ""
    for d in skills["domains"]:
        nc = len((bank.get(d["id"]) or {}).get("cards") or [])
        t += (f'\n### {d["name"]} {{#area-{d["id"]}}}\n\nNamed in **{d["pct_any"]:.0f}%** of postings. '
              f'[Area page: checklist and {nc} questions](../skills/{d["id"]}.qmd).\n\n'
              "| Skill | All postings | MLE | AI eng | Research eng | Employers naming it most |\n|:--|:--|--:|--:|--:|:--|\n")
        for s in d["skills"]:
            bt = s["by_track"]
            t += (f'| [{md_cell(s["name"])}](../skills/{d["id"]}.qmd#{s["id"]}) | {bar(s["pct"])} | {bt.get("mle", 0):.0f}% | '
                  f'{bt.get("ai-engineer", 0):.0f}% | {bt.get("research-engineer", 0):.0f}% | {md_cell(", ".join(s["companies"][:4]))} |\n')
        t += f"\n{{{{< include _prose/{d['id']}.md >}}}}\n"
    g["areas"] = t

    y = summary["yoe"]
    t = "| Years asked | " + " | ".join(("12+" if int(k) == 12 else str(k)) for k in y["hist"]) + " |\n|:--|" + "--:|" * len(y["hist"]) + "\n"
    t += "| Postings | " + " | ".join(str(v) for v in y["hist"].values()) + " |\n"
    g["yoe"] = t

    def pay_rows(title, rows, namemap):
        t = f"| {title} | Postings with a range | Median low end | Median high end | 90th-percentile high end |\n|:--|--:|--:|--:|--:|\n"
        for k, v in rows.items():
            if v:
                t += f'| {namemap.get(k, k)} | {v["n"]} | ${v["low_median"] / 1000:.0f}k | ${v["high_median"] / 1000:.0f}k | ${v["high_p90"] / 1000:.0f}k |\n'
        return t

    p = summary["pay"]
    g["pay_level"] = pay_rows("Level in title", {k: p["by_level"].get(k) for k in ("senior", "staff", "principal", "unlevelled")}, names["level"])
    g["pay_group"] = pay_rows("Employer type", p["by_group"], names["group"])
    g["pay_track"] = pay_rows("Track", p["by_track"], names["track"])

    t = "| Employer | Postings analysed |\n|:--|--:|\n" + "".join(f"| {c} | {k} |\n" for c, k in summary["top_companies"][:40])
    g["companies"] = t

    # coverage: skills -> cards and notes
    t = "| Area | Skills | Skills with cards | Cards | Deep-dive notes |\n|:--|--:|--:|--:|--:|\n"
    for d in skills["domains"]:
        b = bank.get(d["id"]) or {}
        have = {c["skill"] for c in b.get("cards") or []}
        t += (f'| [{d["name"]}](../skills/{d["id"]}.qmd) | {len(d["skills"])} | {sum(s["id"] in have for s in d["skills"])} | '
              f'{len(b.get("cards") or [])} | {len(b.get("notes") or [])} |\n')
    if "cases" in bank:
        t += f'| [Design cases](../skills/cases.qmd) | | | {len(bank["cases"]["cards"])} | |\n'
    g["coverage"] = t

    # high-demand skills without a deep-dive note: the writing backlog
    noted_areas = {a for a, b in bank.items() if b.get("notes")}
    rows = [s for s in top if s["area"] not in noted_areas and s["area"] != "senior"][:15]
    g["backlog"] = "".join(f'- {s["name"]} ({s["pct"]:.0f}% of postings; {SHORT[s["area"]]})\n' for s in rows) or "- None.\n"
    return g


def fetched_local(iso: str) -> str:
    import datetime as dt
    d = dt.datetime.fromisoformat(iso).astimezone()
    return f"{d.day} {d.strftime('%B %Y')}"


def variables(skills, summary, bank) -> str:
    flat = {s["id"]: s for d in skills["domains"] for s in d["skills"]}
    dom = {d["id"]: d for d in skills["domains"]}
    v = dict(
        n_postings=skills["n"], n_raw=summary["raw_postings"], n_unique=summary["unique_postings"],
        n_companies=summary["companies"], n_boards=summary["boards"],
        n_skills=len(flat), n_areas=len(dom),
        n_cards=sum(len(b.get("cards") or []) for b in bank.values()),
        n_cases=len((bank.get("cases") or {}).get("cards") or []),
        fetched=fetched_local(max(x for x in summary["fetched"].values() if x)),
        us_share=f'{summary["us_share"]:.0f}', phd_share=f'{summary["phd_share"]:.0f}',
        yoe_median=f'{summary["yoe"]["median"]:.0f}', yoe_share=f'{summary["yoe"]["share_stated"]:.0f}',
        skills_per_posting=f'{summary["skills_per_posting"]:.0f}',
        dropped_not_ml=summary["dropped"].get("not an ML role by content", 0),
        dropped_junior=summary["dropped"].get("below senior", 0),
    )
    for t in summary["dims"]["track"]:
        v["n_" + t.replace("-", "_")] = summary["dims"]["track"][t]
        v["phd_" + t.replace("-", "_")] = f'{summary["phd_by_track"][t]:.0f}'
    for l, c in summary["dims"]["level"].items():
        v["n_level_" + l] = c
        v["yoe_" + l] = f'{summary["yoe"]["by_level"][l]:.0f}'
    for sid, s in flat.items():
        key = sid.replace("-", "_")
        v["p_" + key] = f'{s["pct"]:.0f}'
        for tk, _, short in TRACKS:
            v[f"p_{key}_{short}"] = f'{s["by_track"].get(tk, 0):.0f}'
        for lv, share in s["by_level"].items():
            v[f"lv_{key}_{lv}"] = f"{share:.0f}"
    for aid, c in summary["dims"]["archetype"].items():
        v["n_arch_" + aid.replace("-", "_")] = c
    for gid, c in summary["dims"]["group"].items():
        v["n_group_" + gid.replace("-", "_")] = c
    for did, d in dom.items():
        v["a_" + did] = f'{d["pct_any"]:.0f}'
    return "# Generated by tools/build_site.py from data/*.json\n" + yaml.safe_dump(v, sort_keys=True, allow_unicode=True)


def main():
    skills, summary, postings, bank = load()
    n = skills["n"]
    skill_names = {s["id"]: s["name"] for d in skills["domains"] for s in d["skills"]}
    for d in skills["domains"]:
        write(f"skills/{d['id']}.qmd", area_page(d, bank.get(d["id"]), skill_names, n))
    if "cases" in bank:
        write("skills/cases.qmd", cases_page(bank["cases"]))
    write("skills/index.qmd", skills_index(skills, bank, n, summary))
    write("review/index.qmd", review_page(skills, bank, skill_names))
    write("review/skills.js", skills_js(skills, bank))
    write("jobs/postings.js", postings_js(postings, summary))
    for k, text in report_tables(skills, summary, bank, skill_names).items():
        write(f"report/_gen/{k}.md", text)
