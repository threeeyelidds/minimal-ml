"""Generate the data-driven pages of the site.

Inputs   bank/*.yml, data/skills.json, data/summary.json, data/postings.json, tools/taxonomy.py
Outputs  skills/index.qmd, skills/<area>.qmd   skill map and one page per area
         review/index.qmd, review/skills.js    review app page (every card) and its skill metadata
         jobs/postings.js                      posting metadata for the jobs browser
         report/_gen/*.md                      tables included by report/index.qmd and plan/index.qmd
         _variables.yml                        headline numbers used in prose via {{< var name >}}

Runs as the Quarto pre-render step and can be run by hand:

    python tools/build_site.py
"""

